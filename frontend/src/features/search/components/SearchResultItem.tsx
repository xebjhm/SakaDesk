import React from 'react';
import DOMPurify from 'dompurify';
import { MessageSquare, FileText, Volume2, Video } from 'lucide-react';
import { cn } from '../../../utils/classnames';
import { formatName } from '../../../utils';
import { getServicePrimaryColor } from '../../../data/services';
import { groupMarkerStyle } from '../groupMarker';
import type { SearchResult } from '../types';

interface SearchResultItemProps {
  result: SearchResult;
  isSelected: boolean;
  onSelect: (result: SearchResult) => void;
  onMouseEnter: () => void;
  userNickname?: string;
}

function formatDate(timestamp: string): string {
  const date = new Date(timestamp);
  const month = (date.getMonth() + 1).toString().padStart(2, '0');
  const day = date.getDate().toString().padStart(2, '0');
  return `${date.getFullYear()}/${month}/${day}`;
}

function truncate(text: string, maxLength: number): string {
  if (text.length <= maxLength) return text;
  return text.slice(0, maxLength) + '...';
}

function formatSegmentTime(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60).toString().padStart(2, '0');
  return `[${m}:${s}]`;
}

function getMessageIcon(type: string) {
  switch (type) {
    case 'voice': return Volume2;
    case 'video': return Video;
    default: return MessageSquare;
  }
}

export const SearchResultItem: React.FC<SearchResultItemProps> = ({
  result,
  isSelected,
  onSelect,
  onMouseEnter,
  userNickname,
}) => {

  const snippet = result.snippet;

  // Replace %%% / ％％％ placeholders with the user's nickname
  const placeholderRegex = /%%%|％％％/g;
  const processedSnippet = userNickname && snippet
    ? snippet.replace(placeholderRegex, userNickname)
    : snippet;
  const rawContent = result.result_type === 'message' ? result.content : null;
  const processedContent = userNickname && rawContent
    ? rawContent.replace(placeholderRegex, userNickname)
    : rawContent;

  const isVoiceOrVideo =
    result.result_type === 'message' &&
    (result.type === 'voice' || result.type === 'video');

  const segmentPrefix =
    isVoiceOrVideo && result.segment_start != null
      ? formatSegmentTime(result.segment_start) + ' '
      : '';

  const displayContent =
    result.result_type === 'message'
      ? (processedSnippet != null
          ? segmentPrefix + processedSnippet
          : processedContent
            ? segmentPrefix + truncate(processedContent, 100)
            : '')
      : processedSnippet ?? '';

  const MessageIcon =
    result.result_type === 'message' ? getMessageIcon(result.type) : null;

  const formattedDate =
    result.result_type === 'message'
      ? formatDate(result.timestamp)
      : new Date(result.published_at).toLocaleDateString('ja-JP');

  return (
    <div
      className={cn(
        'flex w-full cursor-pointer items-start gap-3 rounded-card px-3 py-2 text-left transition-colors duration-fast ease-standard',
        isSelected ? 'bg-accent-subtle' : 'hover:bg-sunken'
      )}
      onClick={() => onSelect(result)}
      onMouseEnter={onMouseEnter}
    >
      <span aria-hidden="true" className="mt-2 h-1.5 w-1.5 shrink-0 rounded-pill bg-group-marker" style={groupMarkerStyle(getServicePrimaryColor(result.service))} />

      <div className="min-w-0 flex-1">
        <div className="flex items-baseline gap-2">
          <span lang="ja" className="truncate text-small font-semibold text-primary">{formatName(result.member_name)}</span>
          {result.result_type === 'message' && (
            <>
              <span className="shrink-0 text-caption text-muted">&middot;</span>
              <span lang="ja" className="truncate text-caption text-muted">{result.group_name}</span>
            </>
          )}
        </div>
        {result.result_type === 'blog' && result.title && (
          <p lang="ja" className="mt-1 truncate text-small font-semibold text-primary">{result.title}</p>
        )}
        {displayContent && (
          processedSnippet ? (
            // Snippet HTML contains <mark> tags generated by the search backend
            // for keyword highlighting. Sanitized with DOMPurify to prevent XSS.
            <p
              lang="ja"
              className="search-snippet mt-1 line-clamp-2 text-small text-secondary [&_mark]:rounded-tail [&_mark]:bg-mark-exact [&_mark]:px-1 [&_mark]:text-inherit [&_mark.reading]:border-b-2 [&_mark.reading]:border-dashed [&_mark.reading]:border-mark-underline [&_mark.reading]:bg-mark-reading"
              dangerouslySetInnerHTML={{ __html: DOMPurify.sanitize(processedSnippet.replace(/\r?\n/g, ' '), { ALLOWED_TAGS: ['mark'], ALLOWED_ATTR: ['class'] }) }}
            />
          ) : (
            <p lang="ja" className="mt-1 line-clamp-2 text-small text-secondary">{displayContent}</p>
          )
        )}
      </div>

      {MessageIcon ? (
        <MessageIcon aria-hidden="true" className="h-4 w-4 shrink-0 text-muted" />
      ) : (
        <FileText aria-hidden="true" className="h-4 w-4 shrink-0 text-muted" />
      )}

      <span className="shrink-0 text-caption tabular-nums text-muted">{formattedDate}</span>
    </div>
  );
};
